-- Переименование служебного сид-аккаунта после миграции провайдера sunor.cc → TTAPI.
--
-- Старое имя 'default@sunor.pool' путало: в админке оно выглядело как реальный
-- аккаунт sunor с «балансом» 1 000 000 кредитов. На деле это локальный
-- служебный аккаунт-ограничитель пула. При единой модели авторизации TTAPI
-- (общий SUNO_API_KEY) реальные кредиты живут в кабинете TTAPI, а token_balance
-- здесь — лишь soft-счётчик, не дающий аккаунту «закончиться» искусственно.
--
-- Меняем только сам сид-аккаунт, не трогая реальные аккаунты администратора.
-- token_balance подтягиваем до большого значения на случай, если он успел
-- просесть из-за ConsumeTokens на старых заказах.
UPDATE suno_accounts
SET email = 'default@numaestra.pool',
    token_balance = GREATEST(token_balance, 1000000),
    updated_at = NOW()
WHERE email = 'default@sunor.pool';
