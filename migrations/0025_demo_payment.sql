-- Платное демо: 50 ₽ за короткий фрагмент, которые засчитываются в счёт песни.
--
-- Раньше демо было бесплатным и выдавалось всем подряд (~3 оплаты на 100 демо —
-- см. 0022). Теперь демо — обязательный первый шаг воронки, но платный: клиент
-- платит символические 50 ₽, слушает фрагмент, затем доплачивает остаток
-- (990 − 50 = 940 ₽). Итоговая сумма для клиента не меняется — 990 ₽.
--
-- У заказа появляется ВТОРАЯ платёжная полоса: собственный InvId в Robokassa,
-- своя сумма и свой статус. Основная полоса (invoice_id / amount_kopecks /
-- payment_status) не трогается — промокоды, сверки и возвраты продолжают
-- работать по полной цене заказа, а к доплате идёт остаток.
ALTER TABLE orders
    -- Отдельный InvId Robokassa под платёж за демо. Берётся из той же
    -- последовательности, что и invoice_id, поэтому в пределах мерчанта уникален
    -- глобально и вебхук однозначно резолвится в нужную полосу.
    -- NULL — заказ создан до этой миграции (или бесплатный по промокоду 100%):
    -- такой заказ оплачивается одним платежом на полную сумму, как раньше.
    ADD COLUMN IF NOT EXISTS demo_invoice_id     BIGINT,
    -- Снапшот цены демо на момент создания заказа: смена DEMO_PRICE_KOPECKS не
    -- должна ломать сверку суммы в вебхуке по уже выставленным счетам.
    ADD COLUMN IF NOT EXISTS demo_amount_kopecks BIGINT NOT NULL DEFAULT 0,
    -- pending → paid | failed | refunded. Значения совпадают с payment_status.
    ADD COLUMN IF NOT EXISTS demo_payment_status VARCHAR(20) NOT NULL DEFAULT 'pending';

-- Уникальность demo_invoice_id как частичный индекс: NULL-заказы (легаси и
-- бесплатные) не конфликтуют друг с другом, а вебхук по InvId находит ровно один
-- заказ. Он же обслуживает поиск GetByDemoInvoiceID.
CREATE UNIQUE INDEX IF NOT EXISTS orders_demo_invoice_id_key
    ON orders (demo_invoice_id)
    WHERE demo_invoice_id IS NOT NULL;
